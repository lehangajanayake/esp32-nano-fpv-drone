#!/usr/bin/env python3
"""Turn exports/shield.net.xml (KiCad XML netlist) into exports/shield-netlist.md
and diff it against the design intent in docs/shield-pcb-requirements.md section 5.

Usage:  python3 scripts/netlist_md.py   (from hardware/shield/)
"""
import os
import re
import xml.etree.ElementTree as ET

HERE = os.path.dirname(os.path.abspath(__file__))
PROJ = os.path.dirname(HERE)

# Section 5 of the requirements, pin by pin. Q5 drain "pins 5 to 8 and pad" is pad 5 in
# KiCad's Diodes_PowerDI3333-8 footprint (all drain copper merged into one pad).
R = lambda r: [r + ".1", r + ".2"]
EXPECTED = {
    "BAT_IN": ["BAT1.1", "Q5.5"],
    "VBAT_P": ["Q5.1", "Q5.2", "Q5.3", "C8.1", "C9.1", "C10.1", "C11.1",
               "MOT1.1", "MOT2.1", "MOT3.1", "MOT4.1", "D1.1", "D2.1", "D3.1", "D4.1",
               "D5.2", "U2.1", "U2.3", "C5.1", "C6.1", "R9.1", "TP1.1"],
    "PGND": ["BAT1.2", "Q1.2", "Q2.2", "Q3.2", "Q4.2", "C8.2", "C9.2", "C10.2", "C11.2",
             "R5.2", "R6.2", "R7.2", "R8.2", "R12.2", "NT1.1"],
    "GND": ["NT1.2", "J2.2", "U1.2", "U1.3", "U1.6", "U1.7", "U2.2", "C1.2", "C2.2", "C3.2",
            "C4.2", "C5.2", "C6.2", "C7.2", "C12.2", "R10.2", "LED1.1", "TP3.1"],
    "Q5_G": ["Q5.4", "R12.1"],
    "XIAO_5V": ["D5.1", "J2.1", "C12.1", "C4.1", "TP4.1"],
    "+3V3_IMU": ["U2.5", "C7.1", "U1.8", "U1.5", "C1.1", "C2.1", "R11.1", "TP2.1"],
    "VBAT_SENSE": ["R9.2", "R10.1", "C3.1", "J1.5"],
    "IMU_INT1": ["U1.4", "J1.6", "TP5.1"],
    "IMU_CS": ["U1.12", "R11.2", "J1.7"],
    "LED_STAT": ["J2.7", "R13.1"],
    "LED_A": ["R13.2", "LED1.2"],
    "SPI_SCK": ["J2.6", "U1.13"],
    "SPI_MISO": ["J2.5", "U1.1"],
    "SPI_MOSI": ["J2.4", "U1.14"],
}
for n in range(1, 5):
    EXPECTED["MOT%d_N" % n] = ["MOT%d.2" % n, "Q%d.3" % n, "D%d.2" % n]
    EXPECTED["PWM%d" % n] = ["J1.%d" % n, "R%d.1" % n]
    EXPECTED["GATE%d" % n] = ["R%d.2" % n, "Q%d.1" % n, "R%d.1" % (n + 4)]
EXPECTED_NC = ["J2.3", "U1.9", "U1.10", "U1.11"]

ORDER = (["BAT_IN", "VBAT_P", "PGND", "GND", "Q5_G"] + ["MOT%d_N" % n for n in range(1, 5)]
         + ["PWM%d" % n for n in range(1, 5)] + ["GATE%d" % n for n in range(1, 5)]
         + ["XIAO_5V", "+3V3_IMU", "VBAT_SENSE", "IMU_INT1", "IMU_CS", "LED_STAT", "LED_A",
            "SPI_SCK", "SPI_MISO", "SPI_MOSI"])


def refkey(s):
    m = re.match(r"([A-Za-z]+)(\d+)\.(\d+)", s)
    return (m.group(1), int(m.group(2)), int(m.group(3))) if m else (s, 0, 0)


def main():
    root = ET.parse(os.path.join(PROJ, "exports/shield.net.xml")).getroot()
    comps = {c.get("ref"): (c.findtext("value"), c.findtext("footprint"))
             for c in root.iter("comp")}
    nets = {}
    pinname = {}
    for net in root.iter("net"):
        name = net.get("name").lstrip("/")
        # The motor channels are one sub-sheet used 4 times, so their local nets come out as
        # Motor<n>/GATE and Motor<n>/MOT_N; map them back to the section 5 names.
        name = re.sub(r"^Motor(\d)/GATE$", r"GATE\1", name)
        name = re.sub(r"^Motor(\d)/MOT_N$", r"MOT\1_N", name)
        nodes = []
        for nd in net.iter("node"):
            k = "%s.%s" % (nd.get("ref"), nd.get("pin"))
            fn = nd.get("pinfunction") or ""
            fn = re.sub(r"_%s$" % re.escape(nd.get("pin")), "", fn).replace("{", "").replace("}", "")
            pinname[k] = "" if fn in ("", "~", nd.get("pin")) or fn.startswith("Pin_") else fn
            nodes.append(k)
        nets[name] = sorted(nodes, key=refkey)

    actual_nc = sorted([n[0] for name, n in nets.items()
                        if name.startswith("unconnected-") and len(n) == 1], key=refkey)
    real = {k: v for k, v in nets.items() if not k.startswith("unconnected-")}

    lines = ["# Shield net list (generated from the KiCad schematic)", "",
             "Generated by `scripts/netlist_md.py` from `exports/shield.net.xml`, which "
             "`kicad-cli sch export netlist` wrote from `shield.kicad_sch`. Do not edit by hand.", "",
             "Nets are in the order of section 5 of "
             "[shield-pcb-requirements.md](../docs/shield-pcb-requirements.md). "
             "Each entry is `ref.pin (pin name)`.", "",
             "| Net | Pins | Count |", "| --- | --- | --- |"]
    extra = [n for n in real if n not in ORDER]
    for name in ORDER + sorted(extra):
        if name not in real:
            lines.append("| `%s` | **missing from schematic** | 0 |" % name)
            continue
        cells = ", ".join("%s (%s)" % (k, pinname[k]) if pinname[k] else k for k in real[name])
        lines.append("| `%s` | %s | %d |" % (name, cells.replace("_", "\\_"), len(real[name])))
    lines += ["", "**Unconnected pins (no-connect flag or NC pin type):** " +
              ", ".join("%s (%s)" % (k, pinname[k]) if pinname[k] else k for k in actual_nc), ""]

    # ---- diff
    diffs = []
    for name in ORDER:
        exp = set(EXPECTED[name])
        act = set(real.get(name, []))
        if not act:
            diffs.append("`%s`: net missing from the schematic" % name)
            continue
        if exp - act:
            diffs.append("`%s`: missing %s" % (name, ", ".join(sorted(exp - act, key=refkey))))
        if act - exp:
            diffs.append("`%s`: extra %s" % (name, ", ".join(sorted(act - exp, key=refkey))))
    for name in extra:
        diffs.append("`%s`: net not in section 5 (%s)" % (name, ", ".join(real[name])))
    nc_extra = set(actual_nc) - set(EXPECTED_NC)
    nc_missing = set(EXPECTED_NC) - set(actual_nc)
    if nc_missing:
        diffs.append("No-connect expected but connected: " + ", ".join(sorted(nc_missing)))

    lines += ["## Check against requirements section 5", ""]
    if diffs:
        lines += ["- " + d for d in diffs]
    else:
        lines.append("Every net in section 5 matches the schematic pin for pin, with no extra nets "
                     "and every listed no-connect in place.")
    lines += ["",
              "Notes on how the section 5 wording maps to KiCad pins:", "",
              "- GATE1 to GATE4 and MOT1\\_N to MOT4\\_N are `/Motor<n>/GATE` and `/Motor<n>/MOT_N` in KiCad: "
              "the four motor channels are one sub-sheet (`motor_driver.kicad_sch`) used four times.",
              "- Q5 drain \"pins 5 to 8 and pad\" is pad 5 here: KiCad's `Diodes_PowerDI3333-8` "
              "footprint merges all drain copper into one pad, and the symbol has one drain pin.",
              "- \"D1 to D4 cathodes\" are pin 1 (K) of the `Device:D_Schottky` symbol; anodes are pin 2 (A). "
              "LED1 cathode is pin 1 (K), anode pin 2 (A).",
              "- Section 5 lists the XIAO GND as \"J2 pin 13 (XIAO GND)\"; per the socket table in 5.1 "
              "that is socket pin J2.2 (XIAO pin 13).",
              "- Extra unconnected pins beyond section 5's no-connect list: " +
              (", ".join("%s (%s)" % (k, pinname[k]) for k in sorted(nc_extra, key=refkey)) or "none") +
              ". These have the NC pin type in the symbol, so they need no flag.", ""]
    open(os.path.join(PROJ, "exports/shield-netlist.md"), "w").write("\n".join(lines))
    print("\n".join(["DIFFS:"] + (diffs or ["none"])))
    print("extra NC:", sorted(nc_extra))


if __name__ == "__main__":
    main()
